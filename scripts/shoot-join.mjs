// Walks the join flow: ID capture + check, medical card check, bank link, and captures each stage.
import { chromium } from "playwright";
const OUT = ".impeccable/review/join";
import fs from "fs"; fs.mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ channel: "chrome" });
const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.goto("http://localhost:3100/?nogate"); await p.evaluate(() => localStorage.setItem("club-age-ok", "1"));
await p.goto("http://localhost:3100/join", { waitUntil: "networkidle" });
const cont = () => p.getByRole("button", { name: "Continue" }).click();
await cont(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/1-id-empty.png` });
await p.getByRole("button", { name: /sample ID/ }).click();
await p.getByRole("button", { name: /Verify my ID/ }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/2-id-scanning.png` });
await p.getByText("ID verified").waitFor(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/3-id-verified.png`, fullPage: true });
await cont(); await p.waitForTimeout(400);
await p.getByText("Upload my card").click();
await p.getByRole("button", { name: /sample card/ }).click();
await p.getByRole("button", { name: /Verify my card/ }).click();
await p.getByText("Medical card on file").waitFor(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/4-card-verified.png`, fullPage: true });
await cont(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/5-bank-pick.png` });
await p.getByRole("button", { name: "Chase" }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/6-bank-login.png` });
await p.getByRole("button", { name: "Continue to Chase" }).click(); await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/7-bank-verifying.png` });
await p.getByRole("button", { name: "Verify" }).waitFor(); await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/8-bank-code.png` });
await p.getByRole("button", { name: "Verify" }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/9-bank-accounts.png` });
await p.getByRole("button", { name: /Link checking/ }).click();
await p.getByText("linked.").waitFor(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/10-bank-linked.png` });
console.log("continue enabled:", await p.getByRole("button", { name: "Continue" }).isEnabled());
await b.close(); console.log("ok");
