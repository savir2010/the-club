// Walks the guest → gated checkout → member flow and captures each stage.
import { chromium } from "playwright";
import fs from "fs";
const OUT = ".impeccable/review/store";
fs.mkdirSync(OUT, { recursive: true });
const U = "http://localhost:3100";
const b = await chromium.launch({ channel: "chrome" });
const p = await (await b.newContext({ viewport: { width: 1440, height: 940 } })).newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
p.on("console", (m) => m.type() === "error" && console.log("console:", m.text().slice(0, 200)));
const shot = (n, o = {}) => p.screenshot({ path: `${OUT}/${n}.png`, ...o });
await p.goto(`${U}/?nogate&as=guest`, { waitUntil: "networkidle" });
await p.evaluate(() => sessionStorage.clear());
await p.waitForTimeout(900);
await shot("01-landing");
await p.getByRole("link", { name: "Start shopping" }).first().click();
await p.waitForURL("**/shop"); await p.waitForTimeout(1200);
await shot("02-store-guest");
await shot("02b-store-guest-full", { fullPage: true });
await p.locator("#account-button").hover(); await p.waitForTimeout(400);
await shot("03-account-menu-guest");
await p.mouse.move(700, 600); await p.waitForTimeout(300);
await p.goto(`${U}/shop/edb-003`, { waitUntil: "networkidle" }); await p.waitForTimeout(600);
await shot("04-product-guest");
await p.getByRole("button", { name: "Add to cart" }).first().click(); await p.waitForTimeout(700);
await shot("05-cart-guest");
await p.getByRole("link", { name: "Proceed to checkout" }).click();
await p.waitForURL("**/checkout"); await p.waitForTimeout(900);
await shot("06-gate-account");
await p.getByRole("button", { name: "Continue" }).click(); await p.waitForTimeout(400);
await p.getByRole("button", { name: /sample ID/ }).click();
await p.getByRole("button", { name: /Verify my ID/ }).click();
await p.getByText("ID verified").waitFor(); await p.waitForTimeout(300);
await shot("07-gate-id");
await p.getByRole("button", { name: "Continue" }).click(); await p.waitForTimeout(300);
await p.getByText("Book a telehealth visit").click(); await p.waitForTimeout(300);
await shot("08-gate-telehealth");
await p.getByRole("button", { name: "Request visit" }).click(); await p.waitForTimeout(300);
await p.getByRole("button", { name: "Continue" }).click(); await p.waitForTimeout(300);
await p.getByRole("button", { name: "Chase" }).click(); await p.waitForTimeout(300);
await p.getByRole("button", { name: "Continue to Chase" }).click();
await p.getByRole("button", { name: "Verify" }).waitFor(); await p.getByRole("button", { name: "Verify" }).click(); await p.waitForTimeout(300);
await p.getByRole("button", { name: /Link checking/ }).click(); await p.getByText("linked.").waitFor();
await p.getByRole("button", { name: "Continue" }).click(); await p.waitForTimeout(400);
await shot("09-gate-plan");
await p.getByRole("button", { name: /Start membership/ }).click(); await p.waitForTimeout(900);
await shot("10-welcome");
await p.getByRole("button", { name: "Continue to delivery" }).click(); await p.waitForTimeout(700);
await shot("11-order-member");
await p.goto(`${U}/shop`, { waitUntil: "networkidle" }); await p.waitForTimeout(900);
await shot("12-store-member");
await p.locator("#account-button").click(); await p.waitForTimeout(400);
await shot("13-account-menu-member");
await p.getByRole("button", { name: "Sign out" }).click(); await p.waitForTimeout(700);
await p.goto(`${U}/signin?next=/shop`, { waitUntil: "networkidle" }); await p.waitForTimeout(500);
await shot("14-signin");
await p.getByRole("button", { name: "Sign in" }).click(); await p.waitForURL("**/shop"); await p.waitForTimeout(900);
await p.getByRole("button", { name: /dark|theme/i }).first().click().catch(() => {}); await p.waitForTimeout(600);
await shot("15-store-dark");
await p.goto(`${U}/shop?category=Edibles`, { waitUntil: "networkidle" }); await p.waitForTimeout(700);
await shot("16-category");
const m = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
await m.goto(`${U}/shop?nogate&as=guest`, { waitUntil: "networkidle" }); await m.waitForTimeout(900);
await m.screenshot({ path: `${OUT}/17-mobile-store.png` });
await m.goto(`${U}/checkout`, { waitUntil: "networkidle" }); await m.waitForTimeout(900);
await m.screenshot({ path: `${OUT}/18-mobile-gate.png` });
const sw = await m.evaluate(() => document.documentElement.scrollWidth);
console.log("mobile scrollWidth", sw);
await b.close(); console.log("ok");
